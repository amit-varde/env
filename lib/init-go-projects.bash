#!/usr/bin/env bash
# =============================================================================
# File:        lib/init-go-projects.bash
# =============================================================================
#
# DESCRIPTION: Navigate to project and set up environment
#   Navigates to a project directory and sets up its environment. It resolves
#   the project directory as $WORK/<project_name> (else $ANALYSIS/<name>), then picks a workspace file
#   from that directory (prefers
#   <project_name>.code-workspace, then project.code-workspace, then any
#   *.code-workspace). Sets PROJECT_NAME and PROJECT_WORKSPACE,
#   optionally opens the workspace file in your editor ($EDITOR_APP, default
#   Cursor via cursor-ide), and updates the shell prompt.
#
# FUNCTIONS:
#   go_project <project_name> [open_editor]
#       Finds project directory, deactivates any current project, sets new
#       environment, and optionally opens its workspace in your editor.
#
# ARGUMENTS:
#   project_name    Name of the project directory
#   open_editor     Open the workspace in your editor (1=yes, 0=no; default: 1)
#
# ENVIRONMENT VARIABLES USED:
#   WORK            Primary workspace directory containing projects
#   EDITOR_APP      Editor app for the workspace (default Cursor.app)
#   PROJECT_NAME    Set to the active project name
#   PROJECT_WORKSPACE  Set to the active project path
#   TERM_PROGRAM    Used to detect if running in the editor's own terminal
#
# EXIT CODES:
#   0 - Success
#   1 - Project not found or WORK is not set/invalid
#
# USAGE:
#   go_project <project_name>
#   go_project <project_name> 0     # Don't open the editor
#
#   Per-project aliases (go-<project>) are auto-generated by
#   init-project-aliases and remain the user-facing entry points.
#
# EXAMPLES:
#   # Switch to a project (via auto-generated alias)
#   go-my-project
#
#   # Switch without opening the editor (call function directly)
#   go_project my-project 0
#
# NOTES:
#   - Sourced by env.sh; uses the logging helpers from lib/common.bash
#   - Deactivates any active Python virtualenv when switching
#   - Project root must exist at $WORK/<project_name>
#   - Workspace file is optional for shell switching; required only to open the editor
#
# =============================================================================
go_project() {
    if [[ -z "${1:-}" ]]; then
        err "No project name provided."
        info "Usage: go_project <project_name> [open_editor=1]"
        return 1
    fi
    local project_name="$1"
    local open_vscode="${2:-1}"
    local project_path=""
    local workspace_file=""

    # Search $WORK first, then $ANALYSIS as a secondary location.
    local work_dir="${WORK:-}"
    local analysis_dir="${ANALYSIS:-}"

    if [[ -z "$work_dir" && -z "$analysis_dir" ]]; then
        err "Neither \$WORK nor \$ANALYSIS is defined."
        info "Set WORK (and optionally ANALYSIS) to a parent directory of your projects."
        return 1
    fi

    project_path=""
    if [[ -n "$work_dir" && -d "$work_dir/$project_name" ]]; then
        project_path="$work_dir/$project_name"
    elif [[ -n "$analysis_dir" && -d "$analysis_dir/$project_name" ]]; then
        project_path="$analysis_dir/$project_name"
    fi

    if [[ -z "$project_path" ]]; then
        err "Project directory not found under \$WORK or \$ANALYSIS: $project_name"
        info "Projects must exist as \$WORK/<name> or \$ANALYSIS/<name>."
        return 1
    fi

    # Resolve a workspace file inside the selected project directory.
    if [[ -f "$project_path/${project_name}.code-workspace" ]]; then
        workspace_file="$project_path/${project_name}.code-workspace"
    elif [[ -f "$project_path/project.code-workspace" ]]; then
        workspace_file="$project_path/project.code-workspace"
    else
        workspace_file="$(find "$project_path" -maxdepth 1 -type f -name "*.code-workspace" -print -quit 2>/dev/null)"
    fi

    if [[ -n "$workspace_file" ]]; then
        info "Found project workspace: $workspace_file"
    else
        info "No workspace file found in $project_path"
    fi

    if [[ -n "${PROJECT_NAME:-}" ]]; then
        info "Deactivating current project: $PROJECT_NAME"
        deactivate 2>/dev/null || info "No virtual environment to deactivate."
        unset PROJECT_NAME
        unset PROJECT_WORKSPACE
    fi

    # Set new project environment
    export PROJECT_NAME="$project_name"
    export PROJECT_WORKSPACE="$project_path"

    cd "$PROJECT_WORKSPACE" || { err "Failed to change directory to $PROJECT_WORKSPACE"; return 1; }

    # Open the workspace file in your editor ($EDITOR_APP, default Cursor) if requested
    # and not already inside its terminal (TERM_PROGRAM=vscode).
    if [[ "${open_vscode}" -eq 1 ]] && [[ "${TERM_PROGRAM:-}" != "vscode" ]] && [[ -n "$workspace_file" ]]; then
        if declare -F editor_open >/dev/null; then
            editor_open "$workspace_file"
        else
            open -a "${EDITOR_APP:-Cursor.app}" "$workspace_file"
        fi
    elif [[ "${open_vscode}" -eq 1 ]] && [[ -z "$workspace_file" ]]; then
        info "Skipping editor open: no .code-workspace file found for $project_name"
    fi

    # Update prompt if in VSCode
    if [[ "${TERM_PROGRAM:-}" == "vscode" ]]; then
        change_prompt
    fi

    success "Switched to project: $PROJECT_NAME at $PROJECT_WORKSPACE"
    return 0
}
